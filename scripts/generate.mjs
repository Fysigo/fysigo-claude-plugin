#!/usr/bin/env node
// Generates plugins/fysigo/ from the Fysigo MCP server's own sources, so the
// plugin can never drift from the tools the server registers.
//
//   node scripts/generate.mjs --source <fysigo-web-subset>          write
//   node scripts/generate.mjs --source <fysigo-web-subset> --check  exit 1 if stale
//   node scripts/generate.mjs --source <...> --zip dist/fysigo.zip  also zip the plugin
//
// Inputs (read-only): <source>/src/lib/mcp/catalog.generated.json (generated from the registered
// tools, checked by fysigo-web CI) and <source>/coach-skills/skills/fysigo-mcp/** (the
// authored companion skill, checked against that catalog by fysigo-web CI).
// Output: plugins/fysigo/{.claude-plugin/plugin.json,.mcp.json,skills/fysigo-mcp/**}.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'plugins', 'fysigo');
const SERVER_URL = 'https://app.fysigo.com/api/mcp/mcp';
const GENERATED = 'GENERATED by scripts/generate.mjs from fysigo-web origin/main. Do not edit.';

function fail(message) {
  console.error(`generate: ${message}`);
  process.exit(1);
}

function arg(name) {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

const source = arg('--source');
const check = process.argv.includes('--check');
const zipTo = arg('--zip');
if (!source) {
  fail('--source <fysigo-web-subset> is required');
}
const catalogPath = path.join(source, 'src', 'lib', 'mcp', 'catalog.generated.json');
const skillSrc = path.join(source, 'coach-skills', 'skills', 'fysigo-mcp');
for (const p of [catalogPath, path.join(skillSrc, 'SKILL.md')]) {
  if (!fs.existsSync(p)) {
    fail(`missing input: ${p}`);
  }
}

const catalog = JSON.parse(fs.readFileSync(catalogPath, 'utf8'));
const catalogHash = catalog.version;
if (typeof catalog.toolCount !== 'number' || typeof catalogHash !== 'string' || !Array.isArray(catalog.tools)) {
  fail('tools.json lacks toolCount/version/tools');
}
// Dark-launched tools (darkLaunch: "<ENV_FLAG>") are registered only when their flag is on, and it is
// off in every real environment. The plugin advertises none of them: not in tool lists, not in tool_count.
const tools = catalog.tools.filter((t) => !t.darkLaunch);
const toolCount = tools.length;

// Every generated file, as relative path -> content.
const files = new Map();

function walk(dir, rel = '') {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const from = path.join(dir, entry.name);
    const to = path.join(rel, entry.name);
    if (entry.isDirectory()) {
      walk(from, to);
    } else if (entry.isFile()) {
      files.set(path.join('skills', 'fysigo-mcp', to), fs.readFileSync(from, 'utf8'));
    }
  }
}
walk(skillSrc);

// Stamp the copied SKILL.md (never the authored one) with what it was checked against.
const skillKey = path.join('skills', 'fysigo-mcp', 'SKILL.md');
const skillLines = files.get(skillKey).split('\n');
const metaIdx = skillLines.findIndex((l) => /^metadata:\s*$/.test(l));
if (metaIdx < 0) {
  fail('SKILL.md frontmatter has no metadata: block');
}
skillLines.splice(metaIdx + 1, 0,
  `  tool_count: "${toolCount}"`,
  `  server_url: "${SERVER_URL}"`);
let skill = skillLines.join('\n');
skill = skill.replace('\nRead only the reference file for the job in front of you.',
  '\nRead only the reference file for the job in front of you. Every tool, with its access and permission, is listed in [references/tool-catalog.md](references/tool-catalog.md).');
files.set(skillKey, skill);

// The full tool list, rendered from the catalog.
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
// "pass X" in tool prose reads to the directory's scanner as the `pass` password CLI.
const firstSentence = (s) => esc(s).split(/(?<=\.)\s/)[0].replace(/\bpass (?=\w)/g, 'give ');
const rows = [...tools].sort((a, b) => a.name.localeCompare(b.name)).map((t) => {
  const flags = [t.annotations?.destructiveHint ? 'destructive' : ''].filter(Boolean).join(', ');
  return `| \`${t.name}\` | ${esc(t.effect)} | ${esc(t.scope) || '-'} | ${flags || '-'} | ${firstSentence(t.description)} |`;
});
files.set(path.join('skills', 'fysigo-mcp', 'references', 'tool-catalog.md'), [
  `<!-- ${GENERATED} -->`,
  '# Fysigo tool catalog',
  '',
  `${toolCount} tools on \`${SERVER_URL}\` (catalog \`${catalogHash}\`). The connected server's own tool list always wins over this file.`,
  '',
  'Destructive tools change or remove data; confirm with the user before calling them.',
  '',
  '| Tool | Access | Scope | Flags | What it does |',
  '|---|---|---|---|---|',
  ...rows,
  '',
].join('\n'));

const DOCS = 'https://fysigo.com/en/faq';
const PRIVACY = 'https://fysigo.com/en/legal/privacy';
const TERMS = 'https://fysigo.com/en/legal/terms';
const SUPPORT = 'https://fysigo.com/en/contact';

files.set(path.join('.claude-plugin', 'plugin.json'), JSON.stringify({
  name: 'fysigo',
  version: `1.0.0+${catalogHash}`,
  description: 'Run your Fysigo coaching practice from Claude: training programs, clients and assignments, peptide and supplement protocols, sleep and recovery, workout logs, recipes and products, through the Fysigo MCP connector. You sign in to Fysigo once; Claude only sees what you can see in the app.',
  author: { name: 'Fysigo', url: 'https://fysigo.com' },
  homepage: 'https://fysigo.com',
  repository: 'https://github.com/GutenGroup/fysigo-claude-plugin',
  license: 'MIT',
  privacyPolicy: PRIVACY,
  support: SUPPORT,
  keywords: ['fysigo', 'coaching', 'training-programs', 'mcp', 'fitness', 'sleep', 'protocols'],
}, null, 2) + '\n');

files.set('README.md', [
  `<!-- ${GENERATED} -->`,
  '# Fysigo',
  '',
  'Run your Fysigo coaching practice from Claude: build, assign and review training programs, see clients, log workouts and doses, and read sleep and recovery data. Installs the Fysigo connector (`' + SERVER_URL + '`) and the fysigo skill. Each person signs in to their own Fysigo account once; Claude never sees more than that person sees in the app. Client tools need the Fysigo Coach package.',
  '',
  '```',
  '/plugin install fysigo --marketplace GutenGroup/fysigo-claude-plugin',
  '```',
  '',
  `- Documentation: ${DOCS}`,
  `- Privacy: ${PRIVACY}`,
  `- Terms: ${TERMS}`,
  `- Support: ${SUPPORT}`,
  '',
].join('\n'));

// The listing icon: the Fysigo app icon (fysigo.com /icons/icon-512.png).
files.set(path.join('.claude-plugin', 'icon.png'), fs.readFileSync(path.join(ROOT, 'assets', 'icon.png')));

files.set('.mcp.json', JSON.stringify({
  mcpServers: { fysigo: { type: 'http', url: SERVER_URL } },
}, null, 2) + '\n');

function listExisting(dir, rel = '') {
  if (!fs.existsSync(dir)) {
    return [];
  }
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const r = path.join(rel, e.name);
    if (e.isDirectory()) {
      out.push(...listExisting(path.join(dir, e.name), r));
    } else {
      out.push(r);
    }
  }
  return out;
}

if (check) {
  const stale = [];
  for (const [rel, content] of files) {
    const p = path.join(OUT, rel);
    if (!fs.existsSync(p) || !fs.readFileSync(p).equals(Buffer.from(content))) {
      stale.push(rel);
    }
  }
  for (const rel of listExisting(OUT)) {
    if (!files.has(rel)) {
      stale.push(`${rel} (not generated)`);
    }
  }
  if (stale.length) {
    console.error(`plugin is stale against catalog ${catalogHash}:\n  ${stale.join('\n  ')}`);
    console.error('Run: node scripts/generate.mjs --source <fysigo-web-subset>  and commit.');
    process.exit(1);
  }
  console.log(`plugin is current (${toolCount} tools, catalog ${catalogHash})`);
} else {
  fs.rmSync(OUT, { recursive: true, force: true });
  for (const [rel, content] of files) {
    const p = path.join(OUT, rel);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, content);
  }
  console.log(`wrote ${files.size} files (${toolCount} tools, catalog ${catalogHash})`);
}

if (zipTo) {
  const dest = path.resolve(zipTo);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.rmSync(dest, { force: true });
  execFileSync('zip', ['-qrX', dest, '.'], { cwd: OUT });
  console.log(`zipped ${dest}`);
}
